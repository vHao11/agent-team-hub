"""Install a built wheel into a temporary directory and verify packaged UI/resources.

Run using the project's environment with its runtime, MCP and development dependencies.
This checks installation output, including Python's generated bytecode caches.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import zipfile

CHECK = r'''
from pathlib import Path
import asyncio, json, re, sys, tomllib
import teamhub
from teamhub.app import create_app
from teamhub import connection, harness_config, mcp_server
from fastapi.testclient import TestClient
root = Path(sys.argv[1])
assert Path(teamhub.__file__).is_relative_to(root / 'installed')
for module in (connection, harness_config, mcp_server):
    assert Path(module.__file__).is_relative_to(root / 'installed')
config = tomllib.loads(harness_config.render_config('codex'))
assert config['mcp_servers']['agent-team-hub']['args'] == ['-m', 'teamhub.mcp_server']
mcp_tools = asyncio.run(mcp_server.build_server(url='http://127.0.0.1:8765', token='wheel-probe-only').list_tools())
assert len(mcp_tools) >= 47
with TestClient(create_app(root / 'data', demo=True)) as client:
    html = client.get('/')
    assert html.status_code == 200 and 'Team Hub' in html.text
    assets = re.findall(r'(?:src|href)="(/assets/[^\"]+)"', html.text)
    assert len(assets) >= 2
    assert all(client.get(asset).status_code == 200 for asset in assets)
    headers = {'Authorization': 'Bearer demo-lin'}
    assert client.get('/api/v1/work-items', headers=headers).json()['total'] == 6
    capabilities = client.get('/api/v1/capabilities', headers=headers).json()['items']
    script = next(cap for cap in capabilities if cap['kind'] == 'script')
    release = client.get('/api/v1/capabilities/' + script['id'] + '/releases/0.1.0', headers=headers).json()
    assert 'summarize.py' in release['files']
    assert not any('__pycache__' in name or name.endswith('.pyc') for name in release['files'])
    print(json.dumps({'wheel_install': 'passed', 'packaged_ui_assets': len(assets), 'seed_items': 6, 'packaged_capabilities': 'passed', 'packaged_mcp_tools': len(mcp_tools), 'packaged_config_generator': 'passed'}))
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('wheel')
    arguments = parser.parse_args()
    wheel = Path(arguments.wheel).resolve()
    with zipfile.ZipFile(wheel) as archive:
        assert any(name.endswith('/licenses/THIRD_PARTY_NOTICES.txt') for name in archive.namelist())
    with tempfile.TemporaryDirectory(prefix='teamhub-wheel-check-') as temporary:
        target = Path(temporary) / 'installed'
        install = subprocess.run([sys.executable, '-m', 'pip', 'install', '--no-deps', '--target', str(target), str(wheel)], capture_output=True, text=True)
        if install.returncode:
            raise RuntimeError(install.stderr)
        environment = dict(os.environ, PYTHONPATH=str(target))
        checked = subprocess.run([sys.executable, '-c', CHECK, temporary], cwd=temporary, env=environment, capture_output=True, text=True)
        if checked.returncode:
            raise RuntimeError(checked.stderr)
        print(checked.stdout.strip())


if __name__ == '__main__':
    main()
